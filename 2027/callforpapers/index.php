	<h2 ID="CfP" name="Call_for_Particiption">Call for Participation FOSSGIS 2027</h2>

	<p>Die FOSSGIS-Konferenz ist die größte deutschsprachige Konferenz für Open Source Software für Geoinformationen und OpenStreetMap und wird vom 09.–13. März 2027 im audiMAX Heidelberg stattfinden. Konferenzveranstalter sind der gemeinnützige FOSSGIS e.V. und die OpenStreetMap-Community in Kooperation mit dem Geographischen Institut, Abt. Geoinformatik der Universität Heidelberg und der HeiGIT GmbH.</p>

	<p>Freie quelloffene Software, Open Data und Open Science leisten einen wichtigen Beitrag zur Stärkung der Digitalen Souveränität. Ziel der jährlichen Konferenz ist die Verbreitung von Freier Open Source Software (FOSS) für Geoinformationssysteme (GIS). Hier treffen sich Anwender:innen, Entwickler:innen, Wissenschaftler:innen und Interessierte zum gemeinsamen Austausch über GIS-Software, OpenStreetMap (OSM) und neue Projekte und Themen mit Geodatenbezug. Mit Vorträgen, Workshops, Demo-Sessions, Anwender:innentreffen und Gelegenheiten zum Netzwerken und Austausch wird die Veranstaltung vorwiegend in Präsenz stattfinden. Die gleichzeitig stattfindende Firmen- und Projektausstellung ermöglicht einen direkten Kontakt zu Dienstleistern und Projekten.</p>

	<p>Am Samstag, den 13. März werden zwei weitere Events stattfinden: <br>
Der OSM-Samstag und ein Community Sprint, angelehnt an die Code Sprints der internationalen FOSS4G-Konferenzen. Der OSM-Samstag wird im Barcamp-Format von der deutschsprachigen OpenStreetMap-Community gestaltet. Es finden Vorträge und Diskussionsrunden zu aktuellen OSM-Themen statt. Themenvorschläge werden im OSM-/FOSSGIS-Wiki gesammelt und können auch spontan vor Ort erfolgen.<br>
Beim Community Sprint haben Interessierte Gelegenheit an ihren eigenen Projekten zu arbeiten und sich mit anderen auszutauschen.
Um die Kapazitäten zu planen ist eine Anmeldung zur Teilnahme erforderlich.</p>

	<p>Aufgrund des positiven Feedbacks für die 180-minütigen Workshops im letzten Jahr, soll dieses Format beibehalten werden. Dementsprechend ist der Dienstag vor der Konferenz für die langen Worskhops vorgesehen.</p>

	<p><b>Der <a href="https://pretalx.com/fossgis2027/cfp" target="_blank">Call for Participation </a> für die FOSSGIS 2027 ist bis zum 01. November 2026 geöffnet (keine Verlängerung).</b></p>

	<h2>Themenbereiche</h2>
	<p>Die FOSSGIS-Konferenz bedient ein weites Themenfeld, das unter anderem die folgenden Aspekte umfasst:</p>
	<ul>
    	<li>Grundlagen zu Open-Source-GIS und OpenStreetMap</li>
    	<li>Neuigkeiten und Interessantes aus den Open-Source-Projekten</li>
    	<li>OpenStreetMap</li>
    	<li>Praxisberichte</li>
		<li>Umstieg auf Open Source</li>
    	<li>Daten, Datenbanken und Datenprozessierung</li>
    	<li>Routing und Mobilität</li>
    	<li>Barrierefreiheit und Inklusion</li>
    	<li>Raum-zeitliche Analysen und Modelle</li>
    	<li>Rasterdaten und Fernerkundung</li>
    	<li>3D, Drohnen, LIDAR, Geo-AR/VR</li>
    	<li>Kartographie und Visualisierung</li>
    	<li>Offene Standards, z.B. INSPIRE, OGC</li>
    	<li>Geodatenmanagement</li>
    	<li>Open Data, Datenschutz und Lizenzen</li>
    	<li>Ausbildung, Lehre, Open Science</li>
	</ul>


  	<h2>Einreichungstypen</h2>

	<p>Das Konferenzprogramm beinhaltet unterschiedliche Formate.</p>
	<ul>
		<li><strong>Vortrag</strong><br>
Vorträge bilden den Hauptteil der Konferenz. Ein Vortrag ist 20 Minuten lang. Danach sind 5 Minuten Zeit für Fragen.

		<li><strong>Lightning Talk</strong><br>
Ein Lightning Talk bietet Gelegenheit neue Software, neue Projekte oder neue Ideen in 5 Minuten zu präsentieren. Es ist möglich, noch kurz vor und während der Konferenz einen Lightning Talk einzureichen, sofern Kapazitäten im Programm verfügbar sind.

		<li><strong>Demo-Session</strong><br>
Die Demo-Session dient der Vorführung von Software oder Prozessen („Live-Hacking“) und ist 45 Minuten lang. Danach sind 10 Minuten Zeit für Fragen.

		<li><strong>Vortrag mit Paper im Academic Track</strong><br>
Begutachtung im Peer-Review-Verfahren durch das Academic Track-Komitee mit dem Ziel einer zitierfähigen Veröffentlichung eines Full Papers (6-8 Seiten). Der einzureichende Abstract sollte ca. 3.000 Zeichen umfassen. Einreichungen – bzw. die Full-Paper – im Academic-Track werden zusätzlich nach gängigen wissenschaftlichen Kriterien _single blind_ bewertet.

		<li><strong>Workshop</strong><br>
Workshops dienen der Vertiefung eines Themas, z.B. mit praktischen Übungen oder Fallbeispielen. Inhalte und Ziele sowie Anteile von Praxis und Theorie, konkrete Anforderungen an Teilnehmende sowie Zielgruppe (Einsteiger:innen, Fortgeschrittene oder Expert:innen) sollten benannt sein. Die Teilnahme am Workshop ist für Teilnehmende kostenpflichtig. Die Zahl der Teilnehmenden ist begrenzt. Es werden Workshops zu aktuellen und nachgefragten Themen bevorzugt. Für die Workshops gibt es folgende Formate:<br>
- 90-minütiger Workshop von Mittwoch bis Freitag parallel zu den Vorträgen<br>
- 180-minütiger Workshop für umfangreichere Themen am Dienstag (Vortag der Konferenz).

		<li><strong>Community-Session</strong><br>
Eine Community-Session kann in Form von Anwender:innentreffen oder „Birds of a Feather“-Sessions (BoF) stattfinden und ermöglicht Gleichgesinnten und Interessierten, sich konzentriert und selbstorganisiert zu einem bestimmten Thema in 60 Minuten auszutauschen.

		<li><strong>Expert:innenfragestunde</strong><br>
Die Idee des Formats ist, dass Expert:innen für 60 Minuten für Fragen von Teilnehmenden zur Verfügung stehen.

		<li><strong>Studi- und Azubi-Session</strong><br>
Auszubildende und Studierende können eine Abschluss-, Seminar-, Projektarbeit als Kurzvortrag vorstellen. Ausführliche Informationen sind in diesem <a href="https://files.fossgis.de/Konferenz/2027/CallforStudents_FOSSGIS-2027.pdf">PDF</a> zu finden.

		<li><strong>Poster-Session</strong><br>
Die Poster-Session bietet eine Plattform, um innovative Ideen, laufende (Forschungs-)Projekte und Studienarbeiten in einem interaktiven Format vorzustellen. Das Posterformat kann dabei zwischen A0 bis A2 gewählt werden. Zusätzlich besteht die Option, einen Kurzbeitrag (max. 3 Seiten) einzureichen, der im Tagungsband veröffentlicht wird.

		<li><strong>Sonstiges</strong><br>
Ihre Einreichung passt nicht zu einem der Einreichungstypen? Dann setzen Sie sich bitte vor dem Ende der Einreichungsfrist mit dem Programm-Komitee <a href="mailto:programm@fossgis.de? subject=Frage%an%das%Programmkomitee">per E-Mail</a> in Verbindung.</li>
		</ul>

  	<h2>Bewertungskriterien</h2>

	<p>Bei der Bewertung der Einreichungen finden folgende Kriterien Anwendung.</p>
	<ul>
	<li>Die Inhalte des Beitrags dienen der Wissensvermittlung und dem Erfahrungsaustausch bezüglich aktueller Themen.</li>

	<li>Bei der Einreichung muss es um freie Software oder freie Daten gehen.</li>
		<ul>
		<li><a href="https://www.gnu.org/licenses/license-list.html">Software ist frei</a>, wenn ihre Lizenzbedingungen von der Free Software Foundation als frei anerkannt werden und der Quellcode öffentlich verfügbar ist.</li>
		<li>Daten sind frei, wenn ihre Lizenzbedingungen der <a href="https://opendefinition.org/" target="_blank">Open Definition</a> entsprechen.</li>
		<li>Der FOSSGIS e.V. unterstützt die Initiative <a href="https://publiccode.eu/de/" target="_blank">Public Money, Public Code</a>. Wir ermuntern alle Projekte und Organisationen, die mit öffentlichen Mitteln freie Software finanzieren, sich und ihre Projekte / Software vorzustellen und von ihren Erfahrungen zu berichten.</li>
		<li>Selbstverständlich freuen wir uns über Beiträge, die die Migration von unfreier zu freier Software oder die Nutzung proprietärer Formate/Schnittstellen mit freier Software thematisieren.</li>
				</ul>
	<li>Vorträge sollten einen Neuigkeitswert bieten und aufzeigen, inwieweit das Thema die Verbreitung von Open Source unterstützt (beispielsweise durch Projektverantwortung (Maintainer), Unterstützung (Contributor), Einsatz/Anwendung (User)).</li>
	<li>Die Einreichung wird nach inhaltlichen Kriterien bewertet. Daher ist für die Bewertung eine aussagekräftige Beschreibung (die mehr Information als die Zusammenfassung enthält) wichtig.</li>
	<li>Eine Einreichung muss von einer oder mehreren natürlichen Personen erfolgen, die den Vortrag / Workshop auch halten.</li>
	<li>Beiträge von Sponsoren werden nicht bevorzugt behandelt, die Vorträge dienen nicht der reinen Firmenpräsentation.</li>
	<li>Werbebeiträge sind unerwünscht.</li>
	<li>Das Ergebnis des Community-Votings wird vom Programmkomitee als Stimmungsbild aus der Community bei der Programmgestaltung einbezogen.</li>
	</ul>

  	<h2>Grundsätze der Programmgestaltung</h2>

	<p>Das Programmkomitee wünscht sich in jeder Hinsicht Diversität unter den Vortragenden. Neue Vortragende sind willkommen! Daher freuen wir uns besonders über Einreichungen von Personen, die noch nicht oder noch nicht oft vorgetragen haben. Sollten Sie unsicher sein, zögern Sie nicht das Programmkomitee zu kontaktieren (<a href="mailto:programm@fossgis.de? subject=Fragen_ans_Programmkomitee">per E-Mail</a>, Telefon: +49 30-62932037)</p>

	<p>Das Programmkomitee ist bestrebt ein ausgewogenes und informatives Programm anzubieten und achtet auf Ausgewogenheit bezüglich Vortragenden und Firmen.</p>
	<p>Die Beiträge werden ausschließlich vor Ort präsentiert. Die Konferenzsprache ist Deutsch. In Ausnahmefällen können Beiträge auf Englisch erfolgen. Falls Themen doppelt eingereicht werden, bemüht sich das Programmkomitee, gemeinsam mit den Einreichenden eine Lösung zu finden.</p>
	<p>Die Vorträge werden live gestreamt sowie die Formate Community-Session und Expert:innenfragestunde hybrid gestaltet. Aus diesem Grund ist es erforderlich, dass alle Vortragenden dem Streaming und der Aufzeichnung ihrer Beiträge zustimmen. Für den Fall, dass Sie keine Aufzeichnung wünschen, kontaktieren Sie bitte das Programmkomitee.</p>

